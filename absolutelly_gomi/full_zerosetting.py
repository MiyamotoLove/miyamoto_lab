import lgpio
import time


# ============================================================
# GPIO設定
# ============================================================

GPIO12 = 12
GPIO13 = 13

FREQUENCY = 50

# ESCのスロットル範囲
FULL_THROTTLE = 2000   # フルスロットル
NEUTRAL = 1500         # ニュートラル


# ============================================================
# GPIO chip
# ============================================================

h = lgpio.gpiochip_open(0)


# ============================================================
# PWM出力関数
# ============================================================

def set_pulse(pulse_us):

    lgpio.tx_servo(
        h,
        GPIO12,
        pulse_us,
        FREQUENCY,
        0,
        0
    )

    lgpio.tx_servo(
        h,
        GPIO13,
        pulse_us,
        FREQUENCY,
        0,
        0
    )

    print(
        f"\rGPIO12 = {pulse_us} us    "
        f"GPIO13 = {pulse_us} us",
        end="",
        flush=True
    )


# ============================================================
# キャリブレーション
# ============================================================

try:

    print("========================================")
    print("      ESC スロットル範囲校正")
    print("========================================")
    print()
    print("⚠ 安全のため履帯を浮かせてください。")
    print("⚠ ESCにバッテリーを接続する前に実行してください。")
    print()
    print("このプログラムは最初に")
    print(f"{FULL_THROTTLE} us（フルスロットル）")
    print("を出力し続けます。")
    print()

    input(
        "準備ができたら Enter を押してください。"
        "\n"
    )

    # --------------------------------------------------------
    # STEP 1
    # フルスロットルを先に出す
    # --------------------------------------------------------

    print()
    print("STEP 1")
    print("フルスロットル信号を出力します。")
    print(f"{FULL_THROTTLE} us")

    set_pulse(FULL_THROTTLE)

    print()
    print()
    print("今、この状態でESCのバッテリーを接続してください。")
    print()

    input(
        "バッテリーを接続したら Enter を押してください。"
    )

    # --------------------------------------------------------
    # STEP 2
    # 接続後2秒待つ
    # --------------------------------------------------------

    print()
    print("ESCの認識待ち...")
    print("2秒待機します。")

    time.sleep(2.0)

    print()
    print("2秒経過しました。")

    # --------------------------------------------------------
    # STEP 3
    # ニュートラルへ
    # --------------------------------------------------------

    print()
    print("STEP 2")
    print("ニュートラル信号へ切り替えます。")
    print(f"{NEUTRAL} us")

    set_pulse(NEUTRAL)

    print()
    print()
    print("ESCのLEDを確認してください。")
    print("フルスロットル確認 → 2回点滅")
    print("ニュートラル確認     → 3回点滅")
    print()
    print("3回点滅すれば校正完了です。")
    print()

    # --------------------------------------------------------
    # ニュートラルを維持
    # --------------------------------------------------------

    while True:

        time.sleep(1)


except KeyboardInterrupt:

    print("\n\n終了します。")


finally:

    # ========================================================
    # ESCをニュートラルにしてから終了
    # ========================================================

    print()
    print("ニュートラル信号を出します。")

    set_pulse(NEUTRAL)

    time.sleep(1)

    # PWM停止
    lgpio.tx_servo(
        h,
        GPIO12,
        0,
        0,
        0,
        0
    )

    lgpio.tx_servo(
        h,
        GPIO13,
        0,
        0,
        0,
        0
    )

    lgpio.gpiochip_close(h)

    print()
    print("終了しました。")